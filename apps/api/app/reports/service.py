"""Interview reports: an on-demand job that turns a finished interview into a
scored, evidence-backed report in ONE structured LLM call. See docs/PHASE9_PLAN.md.

The model proposes 1-5 scores and wording; the overall number, the quote
checks, the coding caps and the 7-day expiry are all decided here, in code."""

import asyncio
import logging
from datetime import UTC, datetime

from fastapi import status

from app.core import jobs as job_runner
from app.core.errors import AppError
from app.db import interviews as interviews_repo
from app.db import reports as reports_repo
from app.db import submissions as submissions_repo
from app.interviews.types import get_config
from app.llm import gateway
from app.llm.budget import truncate
from app.llm.options import LLMOptions
from app.llm.prompts.report import NO_CODE, REPORT_SYSTEM
from app.llm.untrusted import NOTICE, new_boundary, sanitize_derived, wrap
from app.providers.base import Message, MessageRole
from app.reports import scoring
from app.reports.evidence import build_evidence, coding_facts, count_answers
from app.reports.schemas import DIMENSIONS, ReportOut

logger = logging.getLogger(__name__)

REPORT_JOB = "report_generate"
REPORT_DAYS = 7
MIN_ANSWERS = 3
SWEEP_EVERY_SECONDS = 6 * 3600
DISCLAIMER = (
    "This assessment is generated by an AI model from your interview transcript. Treat it as "
    "guidance for practice, not as a verdict on your ability."
)

_OPTIONS = LLMOptions(
    task="report",
    max_output_tokens=1200,
    temperature=0.3,
    feature="interview_report",
    prompt_id="report.v1",
    prompt_version="1",
)

_BRIEF_TOKENS = 200
_SUMMARY_TOKENS = 200


def _now() -> datetime:
    return datetime.now(UTC)


def _parse(ts: str) -> datetime:
    return datetime.fromisoformat(str(ts).replace("Z", "+00:00"))


def is_expired(row: dict, now: datetime | None = None) -> bool:
    """Gone exactly at expires_at (created_at + 7 days)."""
    return _parse(row["expires_at"]) <= (now or _now())


def _summary_row(row: dict) -> dict:
    return {
        "interview_id": row["interview_id"],
        "interview_type": row["interview_type"],
        "overall_score": row["overall_score"],
        "created_at": row["created_at"],
        "expires_at": row["expires_at"],
    }


# --------------------------------------------------------------------- reading


async def purge_expired() -> int:
    try:
        return await reports_repo.purge_expired(_now().isoformat())
    except Exception:
        logger.warning("Could not purge expired reports", exc_info=True)
        return 0


async def list_reports(user_id: str, limit: int = 50, offset: int = 0) -> list[dict]:
    await purge_expired()
    rows = await reports_repo.list_reports(user_id, limit, offset)
    now = _now()
    return [_summary_row(r) for r in rows if not is_expired(r, now)]


async def get_report(user_id: str, interview_id: str) -> dict:
    row = await reports_repo.get_report(user_id, interview_id)
    if not row:
        raise AppError(status.HTTP_404_NOT_FOUND, "not_found", "No report for this interview yet.")
    if is_expired(row):
        # Refuse first, then clean up: expiry never depends on the purge having run.
        await reports_repo.delete_report(user_id, interview_id)
        raise AppError(status.HTTP_410_GONE, "report_expired", "This report has expired and was deleted.")
    return {**_summary_row(row), "report": row["report_data"]}


async def delete_report(user_id: str, interview_id: str) -> None:
    await reports_repo.delete_report(user_id, interview_id)


async def sweep_forever() -> None:
    """Purges expired reports now and every few hours while the server is awake."""
    while True:
        await purge_expired()
        await asyncio.sleep(SWEEP_EVERY_SECONDS)


# ------------------------------------------------------------------ generating


def _messages(interview: dict, config, evidence, facts: list[dict], summary: str | None) -> list[Message]:
    boundary = new_boundary()
    system = REPORT_SYSTEM.format(type_line=config.system_prompt, notice=NOTICE)
    parts = []
    if interview.get("brief"):
        parts.append(wrap("interview_brief", truncate(interview["brief"], _BRIEF_TOKENS), boundary))
    if summary:
        parts.append(wrap("interview_summary", truncate(summary, _SUMMARY_TOKENS), boundary))
    parts.append(wrap("transcript", evidence.transcript, boundary))
    if facts:
        lines = [
            f"Problem {f['problem']} ({f['language']}, {f['line_count']} lines): result {f['result']}; "
            f"issues: {'; '.join(f['issues']) or 'none'}; missed edge cases: "
            f"{'; '.join(f['edge_cases_missed']) or 'none'}; complexity {f['candidate_complexity']} "
            f"vs reference {f['reference_complexity']}."
            for f in facts
        ]
        parts.append(wrap("code_review_notes", "\n".join(lines), boundary))
    else:
        parts.append(NO_CODE)
    parts.append(
        f"Facts: {evidence.answer_count} candidate answers, about {evidence.avg_words} words each on "
        f"average, {evidence.minutes_used} minutes used; answers per phase: "
        + ", ".join(f"{p['phase']}={p['answers']}" for p in evidence.phases)
        + "."
    )
    return [
        Message(role=MessageRole.SYSTEM, content=system),
        Message(role=MessageRole.USER, content="\n\n".join(parts)),
    ]


def assemble(interview: dict, evidence, facts: list[dict], model: ReportOut) -> tuple[dict, int]:
    """Turns the model's proposal into the stored report: verified quotes,
    capped scores, our own overall number."""
    code_results = [f["result"] for f in facts]
    raw = {k: (model.dimensions[k].score if k in model.dimensions else None) for k in DIMENSIONS}
    scores = scoring.apply_caps(raw, code_results)
    overall = scoring.overall_score(interview["type"], scores)

    def checked(quote: str | None) -> str | None:
        return quote if scoring.quote_is_real(quote, evidence.answers) else None

    dimensions = []
    for key in DIMENSIONS:
        dim = model.dimensions.get(key)
        if scores.get(key) is None:
            continue  # unscored: nothing to show (e.g. coding_quality when nothing was submitted)
        dimensions.append(
            {
                "key": key,
                "label": scoring.LABELS[key],
                "score": scores[key],
                "reason": sanitize_derived(dim.reason, 80) if dim else "",
                "quote": checked(dim.quote) if dim else None,
            }
        )

    data = {
        "version": 1,
        "interview": {
            "id": interview["id"],
            "type": interview["type"],
            "started_at": interview.get("started_at"),
            "minutes_used": evidence.minutes_used,
        },
        "overall_score": overall,
        "band": scoring.band(overall),
        "verdict": sanitize_derived(model.verdict, 50),
        "dimensions": dimensions,
        "strengths": [{"point": sanitize_derived(i.point, 60), "quote": checked(i.quote)} for i in model.strengths],
        "improvements": [{"point": sanitize_derived(i.point, 60), "quote": checked(i.quote)} for i in model.improvements],
        "phase_notes": [{"phase": sanitize_derived(n.phase, 20), "note": sanitize_derived(n.note, 60)} for n in model.phase_notes],
        "next_steps": [sanitize_derived(s, 40) for s in model.next_steps],
        "coding": facts,
        "stats": {
            "answers": evidence.answer_count,
            "avg_words": evidence.avg_words,
            "phases": evidence.phases,
            "omitted_turns": evidence.omitted_turns,
        },
        "disclaimer": DISCLAIMER,
    }
    return data, overall


async def begin_report(user_id: str, interview_id: str) -> dict:
    """Returns {"ready": True} if a live report already exists, else starts the
    report job (or joins the one already running) and returns its id."""
    interview = await interviews_repo.get_owned_interview(user_id, interview_id)
    if interview["status"] != "completed":
        raise AppError(
            status.HTTP_409_CONFLICT,
            "interview_not_finished",
            "Finish the interview first -- reports are made for completed interviews.",
        )

    existing = await reports_repo.get_report(user_id, interview_id)
    if existing and not is_expired(existing):
        return {"ready": True, "job_id": None}

    turns = await interviews_repo.transcript(interview_id)
    if count_answers(turns) < MIN_ANSWERS:
        raise AppError(
            status.HTTP_422_UNPROCESSABLE_ENTITY,
            "not_enough_conversation",
            f"There isn't enough conversation to assess yet (at least {MIN_ANSWERS} answers are needed).",
        )

    config = get_config(interview["type"])

    async def work(report) -> dict:
        await report("Gathering the evidence...")
        fresh = await interviews_repo.get_owned_interview(user_id, interview_id)
        evidence = build_evidence(fresh, config, turns)
        submissions = await submissions_repo.finished_for_interview(interview_id)
        facts = coding_facts(submissions, fresh.get("selected_question_ids") or [])

        await report("Writing your report...")
        try:
            model = await gateway.complete_structured(
                user_id,
                fresh["provider"],
                _messages(fresh, config, evidence, facts, fresh.get("running_summary")),
                ReportOut,
                _OPTIONS,
            )
        except gateway.StructuredOutputError as exc:
            logger.warning("Report produced no usable output: %s", exc)
            raise AppError(
                status.HTTP_502_BAD_GATEWAY,
                "report_failed",
                "Couldn't write the report this time -- nothing was saved, please try again.",
            ) from exc

        await report("Checking the details...")
        data, overall = assemble(fresh, evidence, facts, model)
        await reports_repo.save_report(user_id, interview_id, fresh["type"], overall, data)
        return {"interview_id": interview_id}

    job, created = await job_runner.launch(user_id, REPORT_JOB, interview_id, work)
    if not created and job.get("subject_id") != interview_id:
        raise AppError(
            status.HTTP_409_CONFLICT,
            "report_in_progress",
            "Another report is being prepared -- one moment.",
        )
    return {"ready": False, "job_id": job["id"]}

